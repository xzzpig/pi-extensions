export function renderSkill(
  name: OpenspecSkillName,
  context: SkillRenderContext,
): string {
  return `${renderFrontmatter(name, context)}\n\n${SKILL_BODIES[name](context)}\n`;
}

// ── cache & generation ──────────────────────────────────────────────────────

export interface EnsureOpenspecSkillsOptions extends OpenspecCliOptions {
  /** Override the resolved agent dir (tests). Defaults to `resolveAgentDir(env, homeDir)`. */
  agentDir?: string;
  /** Home dir used by agent-dir resolution when `agentDir` is not given. */
  homeDir?: string;
}

export interface EnsureOpenspecSkillsResult {
  /** `<agentDir>/cache/pi-openspec-x/skills/<cliVersion>` — pass as a skill path to pi. */
  skillsDir: string;
  /** CLI version the cache is keyed on. */
  version: string;
  /** True when the versioned directory was already present and valid. */
  cacheHit: boolean;
  /** Absolute SKILL.md paths, one per generated skill. */
  skillFilePaths: string[];
}

const STAMP_FILE_NAME = ".pi-openspec-x-stamp.json";

interface SkillsStamp {
  generatedBy: string;
  skills: string[];
}

function isCacheHit(skillsDir: string, version: string): boolean {
  try {
    const stamp = JSON.parse(
      fs.readFileSync(path.join(skillsDir, STAMP_FILE_NAME), "utf-8"),
    ) as SkillsStamp;
    if (stamp.generatedBy !== version || !Array.isArray(stamp.skills))
      return false;
    return OPENSPEC_SKILL_NAMES.every(
      (name) =>
        stamp.skills.includes(name) &&
        fs.existsSync(path.join(skillsDir, name, "SKILL.md")),
    );
  } catch {
    return false;
  }
}

function generateSkills(
  skillsDir: string,
  context: SkillRenderContext,
): string[] {
  fs.rmSync(skillsDir, { recursive: true, force: true });
  fs.mkdirSync(skillsDir, { recursive: true });
  const skillFilePaths: string[] = [];
  for (const name of OPENSPEC_SKILL_NAMES) {
    const skillDir = path.join(skillsDir, name);
    fs.mkdirSync(skillDir, { recursive: true });
    const filePath = path.join(skillDir, "SKILL.md");
    fs.writeFileSync(filePath, renderSkill(name, context), "utf-8");
    skillFilePaths.push(filePath);
  }
  const stamp: SkillsStamp = {
    generatedBy: context.cliVersion,
    skills: [...OPENSPEC_SKILL_NAMES],
  };
  // The stamp is written last: its presence marks a complete generation.
  fs.writeFileSync(
    path.join(skillsDir, STAMP_FILE_NAME),
    `${JSON.stringify(stamp, null, 2)}\n`,
    "utf-8",
  );
  return skillFilePaths;
}

/**
 * Session-level freeze of the resolved skills directory.
 *
 * Spec: 同一会话内发生 skill 重新发现（如扩展 reload）时，动态 skill 的路径与内容
 * 保持不变，期间发生的 CLI 升级不在本会话生效。 Pi runs one process per session,
 * so pinning the first successful resolution for the process lifetime is exactly
 * that freeze: a re-discovery after an extension reload reuses the pin instead
 * of re-probing the CLI, and a CLI upgrade mid-session therefore cannot swap the
 * skills out from under a running flow.
 */
const frozenSkills = new Map<string, { skillsDir: string; version: string }>();

/** Test-only: drop the session freeze. */
export function resetSkillsFreezeForTests(): void {
  frozenSkills.clear();
}

function frozenResult(frozen: {
  skillsDir: string;
  version: string;
}): EnsureOpenspecSkillsResult {
  return {
    skillsDir: frozen.skillsDir,
    version: frozen.version,
    cacheHit: true,
    skillFilePaths: OPENSPEC_SKILL_NAMES.map((name) =>
      path.join(frozen.skillsDir, name, "SKILL.md"),
    ),
  };
}

/**
 * Ensure the versioned skills cache exists and return its path.
 *
 * Cache hit: directory present, stamp matches the probed CLI version, and
 * every SKILL.md exists — returns without running any schemas/templates
 * command (the version itself comes from the once-per-session probe).
 * Cache miss: probes the version, reads `openspec schemas --json` for the
 * artifact list, and (re)generates all five skills.
 *
 * Throws the typed cli.ts errors; callers decide how to surface them (the
 * resources_discover handler never rethrows).
 */
export function ensureOpenspecSkills(
  options: EnsureOpenspecSkillsOptions = {},
): EnsureOpenspecSkillsResult {
  const agentDir =
    options.agentDir ?? resolveAgentDir(options.env, options.homeDir);
  const cliOptions: OpenspecCliOptions = {
    env: options.env,
    cwd: options.cwd,
    timeoutMs: options.timeoutMs,
    spawnImpl: options.spawnImpl,
  };
  const freezeKey = `${agentDir}::${options.cwd ?? ""}`;
  const frozen = frozenSkills.get(freezeKey);
  if (frozen) return frozenResult(frozen);

  const version = probeOpenspecVersion(cliOptions);
  const skillsDir = openspecXSkillsDir(agentDir, version);
  frozenSkills.set(freezeKey, { skillsDir, version });
  if (isCacheHit(skillsDir, version)) {
    return frozenResult({ skillsDir, version });
  }
  const schemas = listOpenspecSchemas(cliOptions);
  const schema =
    schemas.find((entry) => entry.name === "spec-driven") ?? schemas[0];
  const skillFilePaths = generateSkills(skillsDir, {
    cliVersion: version,
    schema,
  });
  return { skillsDir, version, cacheHit: false, skillFilePaths };
}
