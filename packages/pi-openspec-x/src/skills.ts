/**
 * Official-track skill generation for pi-openspec-x.
 *
 * Generates the five openspec-* SKILL.md files from the installed OpenSpec
 * CLI into `<agentDir>/cache/pi-openspec-x/skills/<cliVersion>/`. The CLI
 * version is the cache key: when the versioned directory exists and its
 * stamp matches, no CLI command runs at all (the version itself comes from
 * the once-per-session probe in cli.ts). On a miss, the artifact list is
 * taken from `openspec schemas --json` (spec-driven -> proposal, specs,
 * design, tasks).
 *
 * The generated bodies are English skeletons that keep the CLI's own flavor:
 * they tell the agent when the skill triggers, sketch the workflow steps, and
 * direct it to fetch the authoritative instructions from the CLI at execution
 * time (`openspec status/list/instructions <artifact> --change <id> --json`).
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { openspecXSkillsDir, resolveAgentDir } from "./agent-dir.ts";
import {
  listOpenspecSchemas,
  probeOpenspecVersion,
  type OpenspecCliOptions,
  type OpenspecSchemaInfo,
} from "./cli.ts";

