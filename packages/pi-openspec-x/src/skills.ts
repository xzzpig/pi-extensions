// ── rendering ───────────────────────────────────────────────────────────────

export interface SkillRenderContext {
  cliVersion: string;
  /** Schema preferred for generation: `spec-driven` when present, else the first reported schema. */
  schema: OpenspecSchemaInfo | undefined;
}

function renderFrontmatter(
  name: OpenspecSkillName,
  context: SkillRenderContext,
): string {
  return [
    "---",
    `name: ${name}`,
    `description: ${SKILL_DESCRIPTIONS[name]}`,
    "allowed-tools: Bash(openspec:*)",
    "license: MIT",
    "compatibility: Requires openspec CLI.",
    "metadata:",
    "  author: openspec",
    '  version: "1.0"',
    `  generatedBy: "${context.cliVersion}"`,
    "---",
  ].join("\n");
}

function renderAuthoritativeBlock(changeScoped: boolean): string {
  const commands = changeScoped
    ? [
        "openspec list --json",
        'openspec status --change "<change-id>" --json',
        'openspec instructions <artifact> --change "<change-id>" --json',
      ]
    : ["openspec list --json", 'openspec status --change "<change-id>" --json'];
  return [
    `This SKILL.md is a generated trigger and workflow skeleton (generated by the pi-openspec-x extension from OpenSpec CLI). The OpenSpec CLI is the single source of truth at execution time: run the \`--json\` commands below fresh in every session and follow their output over anything written here.`,
    "",
    "```bash",
    ...commands,
    "```",
  ].join("\n");
}

function renderArtifactLine(context: SkillRenderContext): string {
  if (!context.schema) {
    return "Run `openspec schemas --json` at execution time to discover the available workflow schemas and their artifacts; none could be captured at generation time.";
  }
  return [
    `Default artifacts for the \`${context.schema.name}\` schema (${context.schema.description}): ${context.schema.artifacts.join(", ")}.`,
    'Always confirm the artifact set with `openspec status --change "<change-id>" --json` at execution time.',
  ].join(" ");
}

